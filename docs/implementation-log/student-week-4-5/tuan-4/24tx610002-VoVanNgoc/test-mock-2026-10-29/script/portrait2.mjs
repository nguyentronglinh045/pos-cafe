import { chromium, newPage, shot } from "./lib.mjs";
const browser = await chromium.launch();
const { page } = await newPage(browser, 390, 844, { touch: true });
page.setDefaultTimeout(8000);
await page.goto("http://127.0.0.1:5175/");
await page.getByTestId("go-store-pairing").click();
await page.getByTestId("store-key-input").fill("0001-X8F3QA");
await page.getByTestId("go-passcode").click();
await page.locator('[data-testid^="employee-"]').filter({ hasText: "Thu ngân" }).first().click();
for (const d of "111111") await page.getByTestId(`pin-${d}`).click();
await page.getByTestId("unlock-button").click();
await page.waitForTimeout(2000);
await shot(page, "P-phone-portrait-after-login");
console.log("portrait after login:", (await page.locator("body").innerText()).replace(/\s+/g, " ").slice(0, 200));
await page.setViewportSize({ width: 844, height: 390 });
await page.waitForTimeout(1500);
await shot(page, "P-phone-rotated-landscape-after-login");
console.log("floor visible after rotate:", await page.getByTestId("floor-view").isVisible().catch(() => false));
await browser.close();
